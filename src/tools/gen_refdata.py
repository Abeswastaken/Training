# Builds lesson/refdata.js from CoolProp (pip install CoolProp). Run: python3 tools/gen_refdata.py
# Units: °F, psia, Btu/lb, Btu/lb·°R, ft³/lb. Reference: ASHRAE (h = s = 0 for saturated liquid at -40°F; bubble point for blends).
import json, CoolProp.CoolProp as CP
FL=[('R-410A','HEOS::R410A'),('R-454B','HEOS::R32[0.8293]&R1234yf[0.1707]'),('R-32','HEOS::R32'),('R-22','HEOS::R22'),('R-134a','HEOS::R134a'),('R-404A','HEOS::R404A')]
K=lambda F:(F-32)/1.8+273.15
psia=lambda P:P/6894.757
hB=lambda h:h/2326.0; sB=lambda s:s/4186.8; vF=lambda v:v*16.01846
out={}
for name,f in FL:
    st=CP.AbstractState(*f.split('::')) if '&' not in f else None
    def P(o,a,b,c,d):
        # the mixture solver sometimes fails at one exact state: nudge the temperature by a few hundredths of a kelvin
        for e in (0,0.01,-0.01,0.03,-0.03,0.08,-0.08,0.15,-0.15):
            try:return CP.PropsSI(o,a,b+(e if a=='T' else 0),c,d,f)
            except Exception:
                if a!='T':raise
        raise ValueError('no solution')
    h0=P('H','T',K(-40),'Q',0);s0=P('S','T',K(-40),'Q',0)
    sat={'T0':-50,'dT':2,'Pb':[],'Pd':[],'hf':[],'hg':[],'sf':[],'sg':[],'vg':[]}
    T=-50
    while T<=160:
        try:
            r=[psia(P('P','T',K(T),'Q',0)),psia(P('P','T',K(T),'Q',1)),hB(P('H','T',K(T),'Q',0)-h0),hB(P('H','T',K(T),'Q',1)-h0),sB(P('S','T',K(T),'Q',0)-s0),sB(P('S','T',K(T),'Q',1)-s0),vF(1/P('D','T',K(T),'Q',1))]
        except Exception as e:
            print(name,'sat stop at',T,str(e)[:60]);break
        for k,v in zip(['Pb','Pd','hf','hg','sf','sg','vg'],r):sat[k].append(v)
        T+=2
    sup={'Td':[],'P':[],'dk':10,'h':[],'s':[],'v':[]}
    for Td in range(-40,151,10):
        Pd=P('P','T',K(Td),'Q',1);hs=[];ss=[];vs=[]
        for k in range(0,201,10):
            if k==0:H=P('H','P',Pd,'Q',1);S=P('S','P',Pd,'Q',1);D=P('D','P',Pd,'Q',1)
            else:H=P('H','P',Pd,'T',K(Td+k));S=P('S','P',Pd,'T',K(Td+k));D=P('D','P',Pd,'T',K(Td+k))
            hs.append(hB(H-h0));ss.append(sB(S-s0));vs.append(vF(1/D))
        sup['Td'].append(Td);sup['P'].append(psia(Pd));sup['h'].append(hs);sup['s'].append(ss);sup['v'].append(vs)
    R=lambda a,n:[round(x,n) for x in a]
    for k,n in [('Pb',2),('Pd',2),('hf',2),('hg',2),('sf',5),('sg',5),('vg',4)]:sat[k]=R(sat[k],n)
    sup['P']=R(sup['P'],2);sup['h']=[R(a,2) for a in sup['h']];sup['s']=[R(a,5) for a in sup['s']];sup['v']=[R(a,4) for a in sup['v']]
    out[name]={'sat':sat,'sup':sup}
    print(name,'rows',len(sat['Pb']),'40F dew psig',round(sat['Pd'][45]-14.696,1),'hf',sat['hf'][45],'hg',sat['hg'][45])
open('lesson/refdata.js','w').write('/* Refrigerant property tables generated by tools/gen_refdata.py from CoolProp (NIST-equivalent equations of state). ASHRAE reference: h = s = 0 for saturated liquid at -40°F. */\nconst REFDATA='+json.dumps(out,separators=(',',':'))+';\n')
